"""
notebooks/colab_train.ipynb (generated by scripts/build_colab_notebook.py)
must resume from the shipped best_v3chain.pt like scripts/train_until_target.sh,
never train/evaluate/export the old best.pt, and never export over the
shipped checkpoints/dead_reckoning_model.onnx.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NB = ROOT / "notebooks" / "colab_train.ipynb"


def _code_cells():
    cells = json.loads(NB.read_text())["cells"]
    return ["".join(c["source"]) for c in cells if c["cell_type"] == "code"]


def _loop_cells():
    # the notebook's own cells, not the %%writefile copies of src/ (whose
    # docstrings and defaults are those files' business)
    return [c for c in _code_cells() if not c.startswith("%%writefile")]


def test_resumes_from_v3chain_not_best_pt():
    loop = "\n".join(_loop_cells())
    assert 'RESUME_FROM = "checkpoints/best_v3chain.pt"' in loop
    assert "checkpoints/best.pt" not in loop
    assert "62.8" not in NB.read_text()


def test_export_cannot_overwrite_shipped_onnx():
    export = [c for c in _loop_cells() if "src.export_onnx" in c]
    assert export, "no export cell"
    for c in export:
        assert 'export_cfg["export"]["onnx_path"] = ONNX_OUT' in c
        assert "--config configs/default.yaml" not in c
    assert "dead_reckoning_model.onnx" not in "\n".join(_loop_cells())


def test_writes_every_module_train_imports():
    written = {c.split("\n", 1)[0].split()[1] for c in _code_cells() if c.startswith("%%writefile")}
    assert "src/chain_eval.py" in written
